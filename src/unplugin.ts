import type { UnpluginFactory } from 'unplugin'
import type { ResolvedConfig } from './content/config'
import type { CollectionDirectory } from './content/entry/node'
import type { MediaConfig } from './types/config/media'
import type { ContentRow } from './types/content/reader'
import type { ForgePressSchema } from './types/core/schema'

import { Buffer } from 'node:buffer'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve as resolvePath } from 'node:path'
import process from 'node:process'
import { createUnplugin } from 'unplugin'
import { resolveConfig } from './content/config'
import { loadConfig } from './content/config/node'
import { readCollections } from './content/entry/node'
import { createMediaStore } from './content/media/node'
import { ENDPOINT, toEntryFile } from './content/paths'
import { findRoot } from './content/root'
import { createWriter } from './content/writer/node'

export interface Options {
  root?: string
  write?: boolean
  media?: MediaConfig
}

const VIRTUAL_ID = 'virtual:forgepress/content'
const LIST_PREFIX = 'virtual:forgepress/list/'

const TYPES = `// Generated by ForgePress. Do not edit.
import type schema from './schema'

declare module 'forgepress' {
  interface ForgePressSchemaRegistry {
    schema: typeof schema
  }
}

export {}
`

function resolved(id: string): string {
  return `\0${id}`
}

function writeTypes(root: string, config: ResolvedConfig): void {
  const path = join(root, config.paths.types)
  const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined

  if (current === TYPES)
    return

  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, TYPES)
}

function entryFile(collection: CollectionDirectory, id: string): string {
  return JSON.stringify(join(collection.path, toEntryFile(id)))
}

function loaders(collection: CollectionDirectory): string {
  const entries = collection.ids.map(id => `      ${JSON.stringify(id)}: () => import(${entryFile(collection, id)}),`)

  return [
    `  ${JSON.stringify(collection.collection)}: {`,
    `    list: () => import(${JSON.stringify(LIST_PREFIX + collection.directory)}),`,
    '    entry: {',
    ...entries,
    '    },',
    '  },',
  ].join('\n')
}

async function generateRoot(root: string, local: boolean, config: ResolvedConfig): Promise<string> {
  const assets = await createMediaStore(root, config.media).list()
  const collections = readCollections(root, config.paths)

  return [
    `export const local = ${local}`,
    `export const provider = ${JSON.stringify(config.provider ?? null)}`,
    `export const format = ${JSON.stringify(config.content ?? null)}`,
    `export const contentPath = ${JSON.stringify(config.paths.dir)}`,
    `export const media = ${JSON.stringify({ ...config.media, assets })}`,
    `export { default as schema } from ${JSON.stringify(join(root, config.paths.schema))}`,
    `export const content = {\n${collections.map(loaders).join('\n')}\n}`,
    '',
  ].join('\n')
}

function generateList(collection: CollectionDirectory): string {
  const imports = collection.ids.map((id, index) => `import entry${index} from ${entryFile(collection, id)}`)
  const items = collection.ids.map((_, index) => `entry${index}`)

  return [...imports, '', `export default [${items.join(', ')}]`, ''].join('\n')
}

function findCollection(root: string, config: ResolvedConfig, directory: string): CollectionDirectory | undefined {
  return readCollections(root, config.paths).find(collection => collection.directory === directory)
}

async function bytes(request: IncomingMessage): Promise<Buffer> {
  const chunks: Buffer[] = []
  for await (const chunk of request)
    chunks.push(chunk as Buffer)

  return Buffer.concat(chunks)
}

async function body(request: IncomingMessage): Promise<unknown> {
  return JSON.parse((await bytes(request)).toString('utf8'))
}

function json(response: ServerResponse, payload: unknown): void {
  response.statusCode = 200
  response.setHeader('content-type', 'application/json')
  response.end(JSON.stringify(payload))
}

async function media(config: ResolvedConfig, root: string, path: string, request: IncomingMessage, response: ServerResponse): Promise<void> {
  const store = createMediaStore(root, config.media)
  const name = decodeURIComponent(path.slice('/media/'.length))

  if (request.method === 'GET')
    return json(response, await store.list())

  if (request.method !== 'DELETE')
    return json(response, await store.write({ name, data: await bytes(request) }))

  await store.remove(name)

  response.statusCode = 204
  response.end()
}

function segments(path: string, prefix: string): string[] {
  return path.slice(prefix.length).split('/').filter(Boolean).map(decodeURIComponent)
}

async function handle(config: ResolvedConfig, root: string, request: IncomingMessage, response: ServerResponse): Promise<void> {
  const path = (request.url ?? '').slice(ENDPOINT.length)
  const writer = createWriter(root, config.paths, config.content)

  if (path === '/media' || path.startsWith('/media/'))
    return media(config, root, path, request, response)

  if (path === '/schema') {
    await writer.writeSchema(await body(request) as ForgePressSchema)
  }
  else if (path.startsWith('/entry/')) {
    const [collection, id] = segments(path, '/entry/')

    if (!collection || !id)
      throw new Error(`unknown endpoint "${path}"`)

    if (request.method === 'DELETE')
      await writer.removeEntry(collection, id)
    else
      await writer.writeEntry(collection, await body(request) as ContentRow)
  }
  else if (path.startsWith('/content/')) {
    const [collection] = segments(path, '/content/')

    if (!collection)
      throw new Error(`unknown endpoint "${path}"`)

    if (request.method === 'DELETE')
      await writer.removeCollection(collection)
    else
      await writer.writeContent(collection, await body(request) as ContentRow[])
  }
  else {
    throw new Error(`unknown endpoint "${path}"`)
  }

  response.statusCode = 204
  response.end()
}

export const unpluginFactory: UnpluginFactory<Options | undefined> = (options) => {
  let root = options?.root ? resolvePath(options.root) : findRoot(process.cwd())
  let local = false

  let config: Promise<ResolvedConfig> | undefined

  async function load(): Promise<ResolvedConfig> {
    const loaded = await loadConfig(root)

    return resolveConfig({ ...loaded, media: { ...loaded?.media, ...options?.media } })
  }

  function resolve(): Promise<ResolvedConfig> {
    config ??= load()

    return config
  }

  return {
    name: 'unplugin-forgepress',

    vite: {
      configResolved(resolvedConfig) {
        root = options?.root ? resolvePath(resolvedConfig.root, options.root) : findRoot(resolvedConfig.root)
        local = resolvedConfig.command === 'serve' && options?.write !== false
      },

      async configureServer(server) {
        const current = await resolve()

        function invalidate(): void {
          const stale = [...server.moduleGraph.idToModuleMap.entries()]
            .filter(([id]) => id.startsWith(resolved('virtual:forgepress/')))
            .map(([, module]) => module)

          if (stale.length === 0)
            return

          for (const module of stale)
            server.moduleGraph.invalidateModule(module)

          server.ws.send({ type: 'full-reload' })
        }

        server.watcher.add(join(root, current.paths.content))
        server.watcher.on('add', invalidate)
        server.watcher.on('unlink', invalidate)

        if (options?.write === false)
          return

        server.middlewares.use((request, response, next) => {
          const method = request.method ?? ''
          const handled = method === 'POST' || method === 'DELETE' || method === 'GET'

          if (!handled || !request.url?.startsWith(`${ENDPOINT}/`))
            return next()

          handle(current, root, request, response)
            .then(invalidate)
            .catch((error: unknown) => {
              response.statusCode = 500
              response.end(error instanceof Error ? error.message : String(error))
            })
        })
      },
    },

    async buildStart() {
      writeTypes(root, await resolve())
    },

    resolveId(id) {
      if (id === VIRTUAL_ID || id.startsWith(LIST_PREFIX))
        return resolved(id)
    },

    async load(id) {
      const current = await resolve()

      if (id === resolved(VIRTUAL_ID))
        return generateRoot(root, local, current)

      if (id.startsWith(resolved(LIST_PREFIX))) {
        const collection = findCollection(root, current, id.slice(resolved(LIST_PREFIX).length))

        return collection ? generateList(collection) : 'export default []\n'
      }
    },
  }
}

